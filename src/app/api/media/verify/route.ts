
import { createHash } from "node:crypto";
import { NextResponse } from "next/server";
import { z } from "zod";
import { getCurrentUser } from "@/lib/current-user";
import { prisma } from "@/lib/prisma";

export const runtime = "nodejs";

const schema = z.object({
  context: z.enum([
    "avatar",
    "brand-logo",
    "portfolio",
    "campaign-cover",
    "campaign-brief",
    "deliverable",
  ]),
  publicId: z.string().min(1).max(240),
  resourceType: z.enum(["image", "video", "raw"]),
  collaborationId: z.string().optional(),
  campaignId: z.string().optional(),
});

function cloudinarySignature(
  params: Record<string, string>,
  secret: string
) {
  const value = Object.keys(params)
    .sort()
    .map((key) => `${key}=${params[key]}`)
    .join("&");

  return createHash("sha1")
    .update(value + secret, "utf8")
    .digest("hex");
}

export async function POST(request: Request) {
  try {
    const user = await getCurrentUser();

    if (!user) {
      return NextResponse.json(
        { error: "Unauthorized" },
        { status: 401 }
      );
    }

    const parsed = schema.safeParse(
      await request.json().catch(() => null)
    );

    if (!parsed.success) {
      return NextResponse.json(
        { error: "Invalid uploaded asset." },
        { status: 400 }
      );
    }

    const {
      context,
      publicId: uploadedPublicId,
      resourceType,
      collaborationId,
      campaignId,
    } = parsed.data;

    // Cloudinary returns the full public ID.
    // Prisma stores only the UUID generated by the signing route.
    const databasePublicId = uploadedPublicId.split("/").pop()!;

    // Reject malformed paths rather than accepting arbitrary public IDs.
    if (
      !databasePublicId ||
      uploadedPublicId.split("/").length < 2
    ) {
      return NextResponse.json(
        { error: "Invalid Cloudinary public ID." },
        { status: 400 }
      );
    }

    console.info("[Cloudinary] Public ID normalization:", {
      uploadedPublicId,
      databasePublicId,
      normalized: uploadedPublicId !== databasePublicId,
    });

    // Find pending authorization using the database UUID.
    const pending = await prisma.mediaAsset.findUnique({
      where: {
        publicId: databasePublicId,
      },
    });

    const ageMs = pending
      ? Date.now() - pending.createdAt.getTime()
      : null;

    console.info("[Cloudinary] Verify authorization diagnostics:", {
      databasePublicId,
      requestedContext: context,
      requestedResourceType: resourceType,
      recordFound: Boolean(pending),
      ownerMatches: pending
        ? pending.ownerUserId === user.id
        : null,
      contextMatches: pending
        ? pending.context === context
        : null,
      resourceTypeMatches: pending
        ? pending.resourceType === "auto"
        : null,
      alreadyLinked: pending
        ? Boolean(pending.linkedAt)
        : null,
      ageMinutes:
        ageMs === null
          ? null
          : Math.round(ageMs / 60000),
      expired:
        ageMs === null
          ? null
          : ageMs > 30 * 60 * 1000,
    });

    if (
      !pending ||
      pending.ownerUserId !== user.id ||
      pending.context !== context ||
      pending.resourceType !== "auto" ||
      pending.linkedAt ||
      pending.createdAt.getTime() < Date.now() - 30 * 60 * 1000
    ) {
      return NextResponse.json(
        {
          error:
            "Upload authorization expired or does not belong to this account. Start the upload again.",
        },
        { status: 403 }
      );
    }

    let expectedPrefix = "";
    let maxBytes = 8 * 1024 * 1024;

    const formats: Record<string, string[]> = {
      avatar: ["jpg", "jpeg", "png", "webp"],
      "brand-logo": ["jpg", "jpeg", "png", "webp"],
      "campaign-cover": ["jpg", "jpeg", "png", "webp"],
      portfolio: [
        "jpg",
        "jpeg",
        "png",
        "webp",
        "mp4",
        "mov",
      ],
      deliverable: [
        "jpg",
        "jpeg",
        "png",
        "webp",
        "mp4",
        "mov",
        "pdf",
        "doc",
        "docx",
      ],
      "campaign-brief": [
        "pdf",
        "doc",
        "docx",
        "ppt",
        "pptx",
        "xls",
        "xlsx",
        "txt",
        "csv",
        "jpg",
        "jpeg",
        "png",
        "webp",
      ],
    };

    // Creator authorization.
    if (context === "avatar" || context === "portfolio") {
      if (user.role !== "CREATOR") {
        return NextResponse.json(
          { error: "Creator account required." },
          { status: 403 }
        );
      }

      const profile = await prisma.creatorProfile.findUnique({
        where: {
          userId: user.id,
        },
        select: {
          id: true,
        },
      });

      if (!profile) {
        return NextResponse.json(
          { error: "Creator profile not found." },
          { status: 404 }
        );
      }

      expectedPrefix =
        `buildin/creators/${user.id}/` +
        `${context === "avatar" ? "avatar" : "portfolio"}/`;

      if (context === "portfolio") {
        maxBytes = 100 * 1024 * 1024;
      }
    }

    // Brand authorization.
    else if (
      context === "brand-logo" ||
      context === "campaign-cover" ||
      context === "campaign-brief"
    ) {
      if (user.role !== "BRAND") {
        return NextResponse.json(
          { error: "Brand account required." },
          { status: 403 }
        );
      }

      const owner = await prisma.brandMember.findFirst({
        where: {
          userId: user.id,
          title: "Owner",
        },
        select: {
          brandId: true,
        },
      });

      if (!owner) {
        return NextResponse.json(
          { error: "Brand owner access required." },
          { status: 403 }
        );
      }

      if (context === "campaign-brief") {
        if (!campaignId) {
          return NextResponse.json(
            { error: "Campaign ID is required." },
            { status: 400 }
          );
        }

        const campaign = await prisma.campaign.findFirst({
          where: {
            id: campaignId,
            brandId: owner.brandId,
          },
          select: {
            id: true,
          },
        });

        if (!campaign) {
          return NextResponse.json(
            { error: "Campaign not found." },
            { status: 404 }
          );
        }

        expectedPrefix =
          `buildin/brands/${owner.brandId}/` +
          `campaigns/${campaignId}/brief/`;

        maxBytes = 25 * 1024 * 1024;
      } else {
        expectedPrefix =
          `buildin/brands/${owner.brandId}/` +
          `${context === "brand-logo" ? "logo" : "campaign-covers"}/`;
      }
    }

    // Collaboration deliverable authorization.
    else {
      if (user.role !== "CREATOR" || !collaborationId) {
        return NextResponse.json(
          { error: "Creator collaboration required." },
          { status: 403 }
        );
      }

      const collaboration =
        await prisma.collaboration.findFirst({
          where: {
            id: collaborationId,
            status: "ACTIVE",
            creatorProfile: {
              userId: user.id,
            },
          },
          select: {
            id: true,
          },
        });

      if (!collaboration) {
        return NextResponse.json(
          { error: "Active collaboration not found." },
          { status: 404 }
        );
      }

      expectedPrefix =
        `buildin/collaborations/${collaboration.id}/deliverables/`;

      maxBytes = 100 * 1024 * 1024;
    }

    // Cloudinary credentials.
    const cloud = process.env.CLOUDINARY_CLOUD_NAME?.trim();
    const key = process.env.CLOUDINARY_API_KEY?.trim();
    const secret = process.env.CLOUDINARY_API_SECRET?.trim();

    if (!cloud || !key || !secret) {
      return NextResponse.json(
        { error: "Cloudinary is not configured." },
        { status: 503 }
      );
    }

    // IMPORTANT:
    // Use the FULL Cloudinary public ID here, not the database UUID.
    const encodedPublicId = uploadedPublicId
      .split("/")
      .map(encodeURIComponent)
      .join("/");

    const adminUrl =
      `https://api.cloudinary.com/v1_1/${cloud}/resources/` +
      `${resourceType}/upload/${encodedPublicId}`;

    console.info("[Cloudinary] Fetching uploaded asset:", {
      resourceType,
      uploadedPublicId,
      adminUrl,
    });

    const response = await fetch(adminUrl, {
      headers: {
        Authorization:
          `Basic ${Buffer.from(`${key}:${secret}`).toString("base64")}`,
      },
      cache: "no-store",
    });

    const asset = await response.json() as {
      public_id?: string;
      bytes?: number;
      format?: string;
      secure_url?: string;
      resource_type?: string;
      error?: {
        message?: string;
      };
    };

    if (!response.ok || !asset.public_id) {
      console.error("[Cloudinary] Admin API verification failed:", {
        status: response.status,
        message: asset.error?.message,
        uploadedPublicId,
        resourceType,
      });

      return NextResponse.json(
        {
          error:
            asset.error?.message ??
            "Unable to verify uploaded file.",
        },
        { status: 502 }
      );
    }

    const imageOnly = [
      "avatar",
      "brand-logo",
      "campaign-cover",
    ].includes(context);

    const format = (asset.format ?? "").toLowerCase();

    const secureUrlValid = (() => {
      try {
        return (
          Boolean(asset.secure_url) &&
          new URL(asset.secure_url!).hostname === "res.cloudinary.com"
        );
      } catch {
        return false;
      }
    })();

    // Validate ownership, folder, size, format and resource type.
    const valid =
      asset.public_id === uploadedPublicId &&
      asset.public_id.startsWith(expectedPrefix) &&
      typeof asset.bytes === "number" &&
      asset.bytes > 0 &&
      asset.bytes <= maxBytes &&
      formats[context].includes(format) &&
      asset.resource_type === resourceType &&
      (!imageOnly || resourceType === "image") &&
      (
        context !== "portfolio" ||
        resourceType === "image" ||
        resourceType === "video"
      ) &&
      secureUrlValid;

    console.info("[Cloudinary] Asset validation:", {
      uploadedPublicId,
      databasePublicId,
      publicIdMatches: asset.public_id === uploadedPublicId,
      folderMatches: asset.public_id.startsWith(expectedPrefix),
      expectedPrefix,
      bytes: asset.bytes,
      maxBytes,
      sizeValid:
        typeof asset.bytes === "number" &&
        asset.bytes > 0 &&
        asset.bytes <= maxBytes,
      format,
      formatValid: formats[context].includes(format),
      resourceTypeMatches:
        asset.resource_type === resourceType,
      imageOnly,
      resourceType,
      secureUrlValid,
      valid,
    });

    if (!valid) {
      // Destroy rejected upload using the FULL Cloudinary public ID.
      const timestamp = String(
        Math.floor(Date.now() / 1000)
      );

      const params = {
        public_id: uploadedPublicId,
        timestamp,
      };

      const form = new FormData();

      form.set("public_id", uploadedPublicId);
      form.set("timestamp", timestamp);
      form.set("api_key", key);
      form.set(
        "signature",
        cloudinarySignature(params, secret)
      );

      const destroyResponse = await fetch(
        `https://api.cloudinary.com/v1_1/${cloud}/${resourceType}/destroy`,
        {
          method: "POST",
          body: form,
          cache: "no-store",
        }
      );

      if (!destroyResponse.ok) {
        console.error(
          "[Cloudinary] Failed to destroy rejected asset:",
          await destroyResponse.text()
        );
      }

      // Delete the pending DB record using its database ID.
      await prisma.mediaAsset.deleteMany({
        where: {
          id: pending.id,
          ownerUserId: user.id,
          linkedAt: null,
        },
      });

      return NextResponse.json(
        {
          error:
            "The uploaded file failed server-side ownership, type, or size validation and was rejected.",
        },
        { status: 400 }
      );
    }

    // Consume pending authorization exactly once.
    // Use the UUID stored in the database.
    const updated = await prisma.mediaAsset.updateMany({
      where: {
        id: pending.id,
        ownerUserId: user.id,
        publicId: databasePublicId,
        context,
        resourceType: "auto",
        linkedAt: null,
      },
      data: {
        resourceType,
        secureUrl: asset.secure_url!,
        bytes: asset.bytes!,
        format: format || "unknown",
      },
    });

    if (updated.count !== 1) {
      return NextResponse.json(
        {
          error:
            "Upload authorization was already used or expired. Start again.",
        },
        { status: 409 }
      );
    }

    console.info("[Cloudinary] Upload verified successfully:", {
      databasePublicId,
      uploadedPublicId,
      userId: user.id,
      context,
      resourceType,
      bytes: asset.bytes,
      format,
    });

    return NextResponse.json({
      ok: true,
      secureUrl: asset.secure_url,
      publicId: uploadedPublicId,
      bytes: asset.bytes,
      format,
      resourceType,
    });
  } catch (error) {
    console.error("[Cloudinary] Verify route error:", error);

    return NextResponse.json(
      { error: "Unable to verify uploaded file." },
      { status: 500 }
    );
  }
}
